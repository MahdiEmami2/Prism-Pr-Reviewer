"""Markdown report rendering.

Contains the ten sections the requirement text lists, in order:

1. metadata; 2. review scope and skipped inputs; 3. executive summary; 4. findings grouped
by severity; 5. exact locations and evidence; 6. why each issue matters; 7. suggested
remediation; 8. recommended tests; 9. analysis limitations; 10. tool and rule versions.

Every untrusted value goes through :mod:`prism.reporting.sanitize` first. PRISM never
claims a report was posted to GitHub; report generation and publishing are separate.
"""

from __future__ import annotations

from collections import OrderedDict
from collections.abc import Iterable, Mapping
from typing import Any

from prism.core.types import CONFIDENCE_MEANING, Confidence, Severity, severity_rank
from prism.findings.models import Finding, ReviewResult
from prism.reporting.sanitize import code_block, escape_table_cell, inline_code, safe_text

SEVERITY_HEADINGS: tuple[tuple[Severity, str], ...] = (
    (Severity.CRITICAL, "Critical"),
    (Severity.HIGH, "High"),
    (Severity.MEDIUM, "Medium"),
    (Severity.LOW, "Low"),
    (Severity.INFORMATIONAL, "Informational"),
)


def render_markdown(result: ReviewResult) -> str:
    """Render the full Markdown report."""
    lines: list[str] = []
    _add = lines.append

    _add(f"# PRISM review report — {safe_text(result.metadata.get('title', 'review'))}")
    _add("")
    _add(
        "> Generated by PRISM, a static analyser. Findings describe what the diff contains. "
        "PRISM does not execute the analysed code and does not prove runtime behaviour."
    )
    _add("")

    _render_metadata(_add, result)
    _render_scope(_add, result)
    _render_summary(_add, result)
    _render_findings(_add, result)
    _render_limitations(_add, result)
    _render_versions(_add, result)
    return "\n".join(lines).rstrip() + "\n"


def _render_metadata(add: Any, result: ReviewResult) -> None:
    add("## 1. Review metadata")
    add("")
    rows: list[tuple[str, Any]] = [
        ("Engine version", result.engine_version),
        ("Review mode", result.mode),
    ]
    for key in sorted(result.metadata):
        rows.append((key, result.metadata[key]))
    if result.generated_at:
        rows.append(("Generated at", result.generated_at))
    add("| Property | Value |")
    add("| --- | --- |")
    for key, value in rows:
        add(f"| {escape_table_cell(key)} | {escape_table_cell(_render_value(value))} |")
    add("")


def _render_value(value: Any) -> str:
    if isinstance(value, (list, tuple)):
        return ", ".join(str(item) for item in value) if value else "(none)"
    if isinstance(value, Mapping):
        return ", ".join(f"{k}={v}" for k, v in sorted(value.items())) or "(none)"
    if value is None:
        return "(none)"
    return str(value)


def _render_scope(add: Any, result: ReviewResult) -> None:
    scope = result.scope
    add("## 2. Review scope and skipped inputs")
    add("")
    add("| Metric | Count |")
    add("| --- | --- |")
    for label, value in (
        ("Files in diff", scope.files_in_diff),
        ("Files analysed", scope.files_analysed),
        ("Files skipped", scope.files_skipped),
        ("Files without deterministic-language rules", scope.files_unsupported_language),
        ("Python files without a parseable view", scope.files_without_full_source),
        ("Added lines", scope.added_lines),
        ("Removed lines", scope.removed_lines),
    ):
        add(f"| {label} | {value} |")
    add("")
    add(f"Review completeness: **{_completeness_label(scope.complete)}**")
    add("")
    if scope.skipped:
        add("### Skipped inputs")
        add("")
        add("| Path | Reason | Detail |")
        add("| --- | --- | --- |")
        for item in scope.skipped:
            add(
                "| {} | {} | {} |".format(
                    escape_table_cell(item.get("path") or "(unknown)"),
                    escape_table_cell(item.get("reason", "")),
                    escape_table_cell(item.get("detail") or ""),
                )
            )
        add("")
    else:
        add("No inputs were skipped.")
        add("")
    if scope.diagnostics:
        add("### Scope diagnostics")
        add("")
        for message in scope.diagnostics:
            add(f"- {safe_text(message, single_line=True)}")
        add("")


def _completeness_label(complete: bool) -> str:
    """One place for the completeness wording, so the report cannot contradict itself."""
    return "complete within the stated limits" if complete else "PARTIAL — a limit was reached"


def _render_summary(add: Any, result: ReviewResult) -> None:
    add("## 3. Executive summary")
    add("")
    counts = result.counts_by_severity
    total = len(result.findings)
    if total == 0:
        add(
            "No findings were produced for the changed lines. This is not a guarantee that "
            "the change is correct: it means no configured rule matched, within the scope "
            "and limits documented below."
        )
    else:
        add(f"{total} finding(s) were produced for the changed lines.")
    add("")
    add("| Severity | Findings |")
    add("| --- | --- |")
    for severity, label in SEVERITY_HEADINGS:
        add(f"| {label} | {counts.get(severity.value, 0)} |")
    add("")
    deterministic = sum(1 for f in result.findings if f.deterministic)
    heuristic = total - deterministic
    add(f"By evidence class: **{deterministic}** deterministic, **{heuristic}** heuristic.")
    add("")
    by_category = result.counts_by_category
    if by_category:
        add("| Category | Findings |")
        add("| --- | --- |")
        for category, count in by_category.items():
            add(f"| {escape_table_cell(category)} | {count} |")
        add("")
    if result.suppressed:
        add(
            f"{len(result.suppressed)} finding(s) were suppressed by configuration; the "
            "suppression reasons are recorded in the JSON report so a short report cannot be "
            "mistaken for a clean one."
        )
        add("")


def _render_findings(add: Any, result: ReviewResult) -> None:
    add("## 4. Findings grouped by severity")
    add("")
    if not result.findings:
        add("(no findings)")
        add("")
        # Sections 5-8 are per-finding. They are still emitted on an empty review so the
        # report always has the same ten sections, and a reader can tell the difference
        # between "nothing to say" and "the section was dropped".
        for heading, body in (
            ("5. Location and evidence", "No finding locations to report."),
            ("6. Why this matters", "No impact notes to report for the changed lines."),
            ("7. Suggested remediation", "No remediation is suggested by the current rules."),
            ("8. Recommended tests", "No test recommendation was produced for this review."),
        ):
            add(f"**{heading}**")
            add("")
            add(body)
            add("")
        return
    grouped: OrderedDict[Severity, list[Finding]] = OrderedDict(
        (severity, []) for severity, _ in SEVERITY_HEADINGS
    )
    for finding in result.findings:
        grouped[Severity(finding.severity)].append(finding)
    for severity, label in SEVERITY_HEADINGS:
        items = grouped[severity]
        if not items:
            continue
        add(f"### {label} ({len(items)})")
        add("")
        for finding in sorted(items, key=lambda f: (f.location.path, f.location.line or -1)):
            _render_finding(add, finding)


def _render_finding(add: Any, finding: Finding) -> None:
    add(f"#### {safe_text(finding.title, single_line=True)}")
    add("")
    add("| Field | Value |")
    add("| --- | --- |")
    # Every cell goes through escape_table_cell: a path or rule id containing '|' would
    # otherwise add columns to the row and corrupt the table.
    add(f"| Finding ID | {escape_table_cell(inline_code(finding.finding_id))} |")
    add(
        f"| Rule | {escape_table_cell(inline_code(finding.rule_id))} "
        f"({escape_table_cell(finding.category)}) |"
    )
    add(f"| Severity | {Severity(finding.severity).value} |")
    add(f"| Confidence | {Confidence(finding.confidence).value} |")
    add(
        f"| Evidence class | {finding.finding_class.value} "
        f"({'deterministic' if finding.deterministic else 'heuristic'}) |"
    )
    location = finding.location
    add(f"| Location | {escape_table_cell(inline_code(location.describe()))} |")
    if location.line is None:
        add("| Line | not derivable from this diff |")
    add("")

    add("**5. Location and evidence**")
    add("")
    add(safe_text(finding.message))
    add("")
    if finding.evidence:
        for snippet in finding.evidence:
            add(code_block(snippet, language="text", limit=1200))
            add("")
    else:
        add("No inline evidence was captured for this finding (the rule reports at file level).")
        add("")
    add("**6. Why this matters**")
    add("")
    add(safe_text(finding.risk) or "_No impact note recorded for this rule._")
    add("")

    add("**7. Suggested remediation**")
    add("")
    add(safe_text(finding.remediation) or "_No remediation recorded for this rule._")
    add("")

    add("**8. Recommended tests**")
    add("")
    if finding.test_recommendation:
        add(safe_text(finding.test_recommendation))
    else:
        add("No specific test recommendation for this rule.")
    add("")
    if finding.confidence is not Confidence.HIGH:
        add(f"_Confidence meaning:_ {CONFIDENCE_MEANING[Confidence(finding.confidence)]}")
        add("")


def _render_limitations(add: Any, result: ReviewResult) -> None:
    add("## 9. Analysis limitations")
    add("")
    for note in result.limitations:
        add(f"- {safe_text(note, single_line=True)}")
    add("")
    coverage = dict(result.coverage)
    add(
        "Coverage data: "
        + (
            "a report was supplied and used for line-explicit statements only."
            if coverage.get("available")
            else "no coverage report was supplied, so no coverage statement is made."
        )
    )
    add("")
    add(
        "PRISM reports findings and does not post them anywhere. Generating a report and "
        "publishing a review comment are separate operations, and this build performs no "
        "publishing."
    )
    add("")


def _render_versions(add: Any, result: ReviewResult) -> None:
    add("## 10. Tool and rule versions")
    add("")
    add("| Component | Version / status |")
    add("| --- | --- |")
    add(f"| PRISM engine | {escape_table_cell(result.engine_version)} |")
    for tool in result.tools:
        add(
            "| {} | status={} version={} exit_code={} findings={} |".format(
                escape_table_cell(tool.name),
                escape_table_cell(tool.status),
                escape_table_cell(tool.version or "(unknown)"),
                tool.exit_code if tool.exit_code is not None else "(n/a)",
                tool.findings_imported,
            )
        )
    add(f"| Rules registered | {len(result.rule_catalog)} |")
    add("")
    if result.rule_catalog:
        add("| Rule | Title | Severity | Confidence | Class |")
        add("| --- | --- | --- | --- | --- |")
        for rule_id in sorted(result.rule_catalog):
            entry = result.rule_catalog[rule_id]
            add(
                "| {} | {} | {} | {} | {} |".format(
                    inline_code(rule_id),
                    escape_table_cell(entry.get("title", "")),
                    escape_table_cell(entry.get("default_severity", "")),
                    escape_table_cell(entry.get("default_confidence", "")),
                    escape_table_cell(entry.get("class", "")),
                )
            )
        add("")
    add("### Documentation")
    add("")
    add("- `docs/ANALYSIS_RULES.md` — rule catalogue with evidence class and false-positive notes.")
    add("- `docs/ARCHITECTURE.md` — module map and data flow.")
    add("- `docs/THREAT_MODEL.md` — untrusted-input boundary and residual risks.")
    add("")


def findings_table(findings: Iterable[Finding]) -> str:
    """Compact one-row-per-finding table, used by the CLI summary."""
    rows = ["| Severity | Rule | Location | Message |", "| --- | --- | --- | --- |"]
    for finding in sorted(findings, key=lambda f: (-severity_rank(f.severity), f.location.path)):
        rows.append(
            f"| {Severity(finding.severity).value} "
            f"| {inline_code(finding.rule_id)} "
            f"| {inline_code(finding.location.describe())} "
            f"| {escape_table_cell(finding.message, limit=160)} |"
        )
    return "\n".join(rows)


__all__ = ["SEVERITY_HEADINGS", "findings_table", "render_markdown"]
